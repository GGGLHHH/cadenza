// Pulls animate-ui's lucide-style animated icons from its shadcn registry into
// src/icons/animate-ui/ and regenerates src/icons/index.ts (served as
// `@gedatou/cadenza-ui/icons`) plus a provenance manifest.
// Re-run to update:  pnpm --filter @gedatou/cadenza-ui sync:icons
//
// animate-ui is MIT + Commons Clause — see ANIMATE-UI-LICENSE.md and README.md.
import { createHash } from 'node:crypto'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const REGISTRY = 'https://animate-ui.com/r'
const PREFIX = 'icons-lucide-'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconsDir = join(root, 'src/icons')
const vendorDir = join(iconsDir, 'animate-ui')

// The one change made to the pulled source: two files import the `Variants`
// type as a value, which this repo's `verbatimModuleSyntax` rejects.
const normalize = content => content.replace(/import \{ motion, Variants \} from 'motion\/react';/, 'import { motion, type Variants } from \'motion/react\';')

const index = await (await fetch(`${REGISTRY}/registry.json`)).json()
const names = index.items.map(item => item.name).filter(name => name.startsWith(PREFIX)).sort()

await rm(vendorDir, { force: true, recursive: true })
await mkdir(vendorDir, { recursive: true })

const manifest = {}
const exportLines = []
// A few at a time: the registry is a static host, not a bulk API.
for (let i = 0; i < names.length; i += 16) {
  await Promise.all(names.slice(i, i + 16).map(async (name) => {
    const res = await fetch(`${REGISTRY}/${name}.json`)
    if (!res.ok)
      throw new Error(`${name}: HTTP ${res.status}`)
    const item = await res.json()
    if (item.files.length !== 1)
      throw new Error(`${name}: expected one file, got ${item.files.length}`)
    const pulled = item.files[0].content
    const content = normalize(pulled)
    const file = `${name.slice(PREFIX.length)}.tsx`
    await writeFile(join(vendorDir, file), content)
    manifest[file] = {
      registry: `${REGISTRY}/${name}.json`,
      sha256: createHash('sha256').update(pulled).digest('hex'),
      ...(content === pulled ? {} : { normalized: 'type-only Variants import' }),
    }

    // Every icon ends with `export { animations, X, X as XIcon, type XProps, … }`.
    // Re-export all but `animations`, which every file names the same.
    const block = content.match(/export \{([^}]+)\};?\s*$/)
    if (!block)
      throw new Error(`${name}: no trailing export block`)
    const specifiers = block[1].split(',').map(s => s.trim()).filter(s => s && s !== 'animations')
    exportLines.push([file, `export { ${specifiers.join(', ')} } from './animate-ui/${file.replace(/\.tsx$/, '')}'`])
  }))
}

exportLines.sort(([a], [b]) => a.localeCompare(b))
await writeFile(join(iconsDir, 'index.ts'), [
  '// Generated by scripts/sync-animate-ui-icons.mjs — do not edit by hand.',
  '// The icons are animate-ui\'s (MIT + Commons Clause, see ANIMATE-UI-LICENSE.md);',
  '// the trigger and the base re-exported below come from its npm package.',
  'export { AnimateIcon, type AnimateIconProps, type IconProps, IconWrapper, type IconWrapperProps } from \'@animate-ui/react/icons\'',
  ...exportLines.map(([, line]) => line),
  '',
].join('\n'))
await writeFile(join(vendorDir, 'manifest.json'), `${JSON.stringify(Object.fromEntries(Object.entries(manifest).sort()), null, 2)}\n`)
console.log(`synced ${names.length} icons`)
