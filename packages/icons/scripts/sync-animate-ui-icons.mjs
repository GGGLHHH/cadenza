// Pulls animate-ui's lucide-style animated icons from its shadcn registry and
// writes each in cadenza-ui's data form (its shapes and animations, rendered
// by src/create-icon.tsx) to src/animate-ui/, then regenerates src/index.ts
// (the package's entry) and a provenance manifest.
// Re-run to update:  pnpm --filter @gedatou/cadenza-icons sync:icons
// `--out <dir>` writes the icons, index and manifest there instead, to see
// what an update would change before taking it.
//
// animate-ui is MIT + Commons Clause — see ANIMATE-UI-LICENSE.md and README.md.
import { createHash } from 'node:crypto'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { iconDataFile } from './icon-to-data.mjs'

const REGISTRY = 'https://animate-ui.com/r'
const PREFIX = 'icons-lucide-'
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFlag = process.argv.indexOf('--out')
const iconsDir = outFlag === -1 ? join(root, 'src') : resolve(process.argv[outFlag + 1])
const vendorDir = join(iconsDir, 'animate-ui')

// The one change made to the pulled source before converting it: two files
// import the `Variants` type as a value, which `verbatimModuleSyntax` rejects.
const normalize = content => content.replace(/import \{ motion, Variants \} from 'motion\/react';/, 'import { motion, type Variants } from \'motion/react\';')

const index = await (await fetch(`${REGISTRY}/registry.json`)).json()
const names = index.items.map(item => item.name).filter(name => name.startsWith(PREFIX)).sort()

await rm(vendorDir, { force: true, recursive: true })
await mkdir(vendorDir, { recursive: true })

const manifest = {}
const exportLines = []
// A few at a time: the registry is a static host, not a bulk API.
for (let i = 0; i < names.length; i += 16) {
  await Promise.all(names.slice(i, i + 16).map(async (name) => {
    const res = await fetch(`${REGISTRY}/${name}.json`)
    if (!res.ok)
      throw new Error(`${name}: HTTP ${res.status}`)
    const item = await res.json()
    if (item.files.length !== 1)
      throw new Error(`${name}: expected one file, got ${item.files.length}`)
    const pulled = item.files[0].content
    const slug = name.slice(PREFIX.length)
    // Throws on anything outside the icon template, so an upstream change is
    // never half-converted.
    const { exportName, text } = iconDataFile(slug, normalize(pulled))
    await writeFile(join(vendorDir, `${slug}.ts`), text)
    manifest[`${slug}.ts`] = {
      registry: `${REGISTRY}/${name}.json`,
      sha256: createHash('sha256').update(pulled).digest('hex'),
    }
    exportLines.push([slug, `export { ${exportName}, type ${exportName}Props } from './animate-ui/${slug}'`])
  }))
}

exportLines.sort(([a], [b]) => a.localeCompare(b))
await writeFile(join(iconsDir, 'index.ts'), [
  '// Generated by scripts/sync-animate-ui-icons.mjs — do not edit by hand.',
  '// The icons are animate-ui\'s (MIT + Commons Clause, see ANIMATE-UI-LICENSE.md),',
  '// in our data form; the trigger and the base come from its npm package.',
  'export { AnimateIcon, type AnimateIconProps, type IconProps } from \'@animate-ui/react/icons\'',
  ...exportLines.map(([, line]) => line),
  '// Ours, not pulled: Tabler shapes on animate-ui\'s stroke draw, for the icons',
  '// the set lacks.',
  'export * from \'./drawn\'',
  '',
].join('\n'))
await writeFile(join(vendorDir, 'manifest.json'), `${JSON.stringify(Object.fromEntries(Object.entries(manifest).sort()), null, 2)}\n`)
console.log(`synced ${names.length} icons`)
