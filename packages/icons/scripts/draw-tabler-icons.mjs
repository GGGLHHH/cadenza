// Writes src/drawn.ts: the shapes animate-ui's set does not draw, taken
// from Tabler (MIT) and put in the same data form as the pulled icons. Each
// shape gets animate-ui's generic stroke draw (`staticAnimations.path`), so the
// icons take every trigger and prop the others do.
// Re-run after changing the list:  pnpm --filter @gedatou/cadenza-icons draw:icons
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as tabler from '@tabler/icons-react'
import { Children } from 'react'

// Our name → Tabler's component.
const DRAWN = {
  AlignCenter: 'IconAlignCenter',
  AlignLeft: 'IconAlignLeft',
  AlignRight: 'IconAlignRight',
  Bold: 'IconBold',
  Brain: 'IconBrain',
  ChevronsLeft: 'IconChevronsLeft',
  ChevronsRight: 'IconChevronsRight',
  Columns: 'IconColumns',
  FileMusic: 'IconFileMusic',
  GitBranch: 'IconGitBranch',
  GripVertical: 'IconGripVertical',
  Hash: 'IconHash',
  Inbox: 'IconInbox',
  Italic: 'IconItalic',
  LayoutGrid: 'IconLayoutGrid',
  Server: 'IconServer',
  Smile: 'IconMoodSmile',
  Stop: 'IconPlayerStop',
  Table: 'IconTable',
  Underline: 'IconUnderline',
  UserPlus: 'IconUserPlus',
  Video: 'IconVideo',
}
const TAGS = new Set(['circle', 'ellipse', 'line', 'path', 'polygon', 'polyline', 'rect'])

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const lines = [
  '\'use client\'',
  '',
  '// Generated by scripts/draw-tabler-icons.mjs — do not edit by hand.',
  '// The shapes animate-ui\'s set does not draw, from Tabler (MIT), in the same',
  '// data form as the pulled icons; each shape draws in with animate-ui\'s',
  '// generic stroke draw.',
  'import type { IconProps } from \'@animate-ui/react/icons\'',
  'import { staticAnimations } from \'@animate-ui/react/icons\'',
  'import { createIcon } from \'./create-icon\'',
  '',
  'export type DrawnIconProps = IconProps<\'default\'>',
  '',
]
for (const [name, source] of Object.entries(DRAWN)) {
  // A Tabler icon is a forwardRef component; its render gives the <svg> and
  // its shapes without mounting anything.
  const svg = tabler[source].render({}, null)
  const shapes = Children.toArray(svg.props.children)
  const nodes = shapes.map((shape, i) => {
    if (!TAGS.has(shape.type))
      throw new Error(`${source}: unsupported <${shape.type}>`)
    return `[${JSON.stringify(shape.type)}, ${JSON.stringify(shape.props)}, "shape${i}"]`
  })
  const animations = `{ default: { ${shapes.map((_, i) => `shape${i}: staticAnimations.path`).join(', ')} } }`
  lines.push(
    `export const ${name}Icon = /* @__PURE__ */ createIcon(${JSON.stringify(`${name}Icon`)}, [${nodes.join(', ')}], ${animations}, { pathStyle: true })`,
  )
}
lines.push('')
await writeFile(join(root, 'src/drawn.ts'), lines.join('\n'))
console.log(`drew ${Object.keys(DRAWN).length} icons`)
