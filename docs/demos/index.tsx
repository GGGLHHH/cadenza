export function DemoRenderer({ name }: { name: string }): ReactElement {
  const Demo = registry[name]

  if (Demo === undefined) {
    return (
      <p className="text-sm text-muted-foreground">
        Demo not found:
        {' '}
        <code>{name}</code>
      </p>
    )
  }

  return (
    <Suspense fallback={null}>
      <Demo />
    </Suspense>
  )
}
